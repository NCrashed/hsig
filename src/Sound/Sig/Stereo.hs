-- | Стерео слоем поверх моно.
--
-- Ядро осталось моно: @Sig@ по разд. 3 это поток блоков одного канала, и
-- ломать его ради двух каналов незачем. Стерео это пара таких сигналов,
-- панорама и запись в два канала.
module Sound.Sig.Stereo
  ( Stereo (..)
  , mono
  , pan
  , orbit
  , bothChannels
  , mixStereo
  ) where

import Sound.Sig.Core
import Sound.Sig.Delay (vdelay)
import Sound.Sig.Filter (onepole)

data Stereo = Stereo
  { leftChan :: Sig
  , rightChan :: Sig
  }

-- | По центру.
mono :: Sig -> Stereo
mono = pan 0

-- | Панорама по закону равной мощности: -1 слева, 0 по центру, 1 справа.
--
-- По центру каждый канал получает 1\/sqrt 2, поэтому мощность не зависит от
-- положения, а сумма каналов по центру громче одиночного канала в sqrt 2.
-- Отсюда и потеря в моно: центр в сумме поднимается в sqrt 2, а края лишь в
-- 1.075, то есть разведённое по краям в моно тише на четверть. Усиления
-- положительные, так что вычитания не бывает. NaN, как и у 'clampCut',
-- прижимается к нижнему краю, то есть влево.
--
-- @s@ входит в определение дважды, но share здесь намеренно нет: канал это
-- сигнал длиной в трек, и share держал бы его целиком в памяти (разд. 3).
-- Каналы читаются поблочно и в шаге, поэтому лишний счёт дешевле памяти.
pan :: Double -> Sig -> Stereo
pan p s = Stereo (s * constant (cos angle)) (s * constant (sin angle))
  where
    angle = (max (-1) (min 1 p) + 1) * pi / 4

-- | Источник, вращающийся вокруг головы. Угол в радианах, 0 это спереди,
-- pi\/2 справа.
--
-- Слух локализует по четырём признакам, тут сделаны три:
--
-- * разница прихода между ушами, до 0.65 мс на сфере радиусом с голову.
--   Главный признак ниже полутора килогерц, и именно он даёт ощущение
--   обхода, а не переливания из канала в канал;
-- * тень головы: дальнее ухо теряет верх, срез едет с 18 кГц до 1.5;
-- * разница уровней, умеренная. Жёсткая панорама по краям звучала бы как
--   выключение канала, а не как источник сбоку.
--
-- Четвёртого признака, спектральных зарубок ушной раковины, тут нет: без
-- них перед и зад на слух не различаются, и полный оборот читается как
-- обход через бока. Лечится это только HRTF или структурной моделью
-- раковины.
--
-- Формат наушниковый. При сведении в моно межушная задержка даёт гребёнку,
-- и глубже всего она не по бокам, а у центра: там уровни ушей почти равны,
-- поэтому пути гасят друг друга сильнее. Замер против ближнего уха: на
-- 10 градусах провал -20.6 дБ на 4.4 кГц, на 90 градусах всего -8.9 дБ
-- около 800 Гц, потому что дальнее ухо там задавлено тенью. При вращении
-- провал ездит по спектру, то есть в моно это слышно как фленджер.
-- Неизбежная цена любой модели с задержкой, у настоящих HRTF ровно то же.
--
-- Длина выхода это минимум длин угла и источника: 'vdelay' и 'onepole'
-- режут по короткому. Последние 0.85 мс источника в дальний канал не
-- попадут, поэтому ноте с релизом нужны 0.85 мс тишины после конца, иначе
-- дальний канал оборвётся ступенькой. Добивают до полной длины:
-- @padSec (dur + 0.00085) note@ - 'padSec' задаёт итоговую длительность, а
-- не прибавку.
--
-- Угол входит в определение шесть раз (три признака на два уха), источник
-- дважды, но share здесь намеренно нет: это сигналы длиной в трек, и
-- держать их целиком дороже, чем посчитать (та же оговорка, что у 'pan').
-- Угол поэтому должен быть дешёвым узлом вроде 'phase'; тяжёлый подграф на
-- нём оплачивается шестикратно.
orbit :: Sig -> Sig -> Stereo
orbit angle s = Stereo (ear (-1)) (ear 1)
  where
    -- side это сторона уха: -1 левое, +1 правое. v это синус угла, он же
    -- смещение источника вправо.
    ear side =
      onepole (sway (cutAt side)) (vdelay (base + maxItd) (sway (arrivalAt side)) s)
        * sway (gainAt side)
    sway f = mapSig (f . sin) angle
    -- Синус и так лежит в [-1, 1], зажим нужен только против NaN: он, как и
    -- в clampCut, уводит в нижний край, а не разносит NaN по всему выходу.
    clamped v = max (-1) (min 1 v)

    -- Ближнее ухо слышит раньше. Общее смещение в 0.2 мс держит время выше
    -- минимума vdelay (8 сэмплов, то есть 0.167 мс при 48 кГц) на всём
    -- обороте. Оно одинаково для обоих ушей, поэтому на образ не влияет, но
    -- это общая задержка тракта: смешивать обработанное с необработанным
    -- нужно с оглядкой.
    --
    -- Из времени вычитается групповая задержка теневого фильтра: он
    -- минимально-фазовый и на низах задерживает на 1/(2*pi*fc), то есть до
    -- 0.106 мс на дальнем ухе. Она садится на то же ухо, которое и так
    -- позднее, поэтому без вычитания складывалась бы с межушной и давала бы
    -- на боках 0.75 мс вместо 0.65 - голову радиусом 10 см вместо 8.75.
    arrivalAt side v =
      base + maxItd * (1 - side * clamped v) / 2 - 1 / (2 * pi * cutAt side v)
    base = 0.0002
    maxItd = 0.00065

    -- Тень головы падает на дальнее ухо. Срез едет по логарифму: на слух
    -- это равномерное закрывание.
    cutAt side v = cutOpen * (cutShut / cutOpen) ** max 0 (negate (side * clamped v))
    cutOpen = 18000
    cutShut = 1500

    -- Закон равной мощности, но неполной глубины: 9.8 дБ по краям.
    gainAt side v = cos ((1 - ildDepth * side * clamped v) * pi / 4)
    ildDepth = 0.6

-- | Обработать оба канала одним и тем же Fx.
bothChannels :: Fx -> Stereo -> Stereo
bothChannels fx (Stereo l r) = Stereo (fx l) (fx r)

-- | Сложить стерео-сигналы.
--
-- Без нейтрального элемента: литеральный 0 бесконечен и растянул бы микс.
mixStereo :: [Stereo] -> Stereo
mixStereo [] = Stereo (fromSamples []) (fromSamples [])
mixStereo (x : xs) = foldl add x xs
  where
    add (Stereo l r) (Stereo l' r') = Stereo (l + l') (r + r')
