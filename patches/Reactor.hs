-- | Реактор: пульсирующие стержни, вращающиеся вокруг головы.
module Reactor
  ( reactor
  , rod
  ) where

import Data.Function ((&))
import Sound.Sig

-- | Стержни на заданных частотах. orbitHz это обороты в секунду, pulseHz
-- вспышки в секунду, spread это доля оборота между соседними стержнями.
--
-- Про spread стоит знать неочевидное. Одновременно звучит ровно один
-- стержень: при трёх стержнях в пике вспышки соседи по фазе дают минус
-- 72 дБ (при шести это уже минус 15, и рассуждение перестаёт работать).
-- Значит слышно не сумму точек, а последовательность вспышек.
--
-- Инвариант: за один период вспышки набор точек продвигается ровно на
-- @orbitHz \/ pulseHz@ оборота при любом spread. Сам spread только
-- раскладывает n вспышек внутри этого периода:
--
-- * @spread = 0@ - вспышки лежат в периоде равномерно, шаг между соседними
--   ровно @orbitHz \/ (n * pulseHz)@, луч ровным шагом обходит голову. Это
--   и нужно;
-- * @spread = orbitHz \/ (n * pulseHz)@ - все n вспышек схлопываются в одну
--   точку. Обход остаётся, но идёт ступенями по @orbitHz \/ pulseHz@, то
--   есть втрое грубее при трёх стержнях;
-- * @spread = 1\/n@ (стержни поровну по кругу, что выглядит правильнее
--   всего) - вспышки разбросаны по кругу, и порядок обхода перемешан. На
--   слух это не вращение, а разброс.
reactor :: Double -> Double -> Double -> [Double] -> Stereo
reactor orbitHz pulseHz spread freqs =
  mixStereo
    [ rod orbitHz pulseHz f (spread * fromIntegral i) (fromIntegral i / n)
    | (i, f) <- zip [0 :: Int ..] freqs
    ]
  where
    n = fromIntegral (max 1 (length freqs))

-- | Один стержень: turn это его место на орбите в долях оборота, flash это
-- сдвиг фазы вспышки в долях периода вспышек.
rod :: Double -> Double -> Double -> Double -> Double -> Stereo
rod orbitHz pulseHz freq turn flash = orbit angle voice
  where
    angle = phase (constant orbitHz) + constant (2 * pi * turn)

    -- Вспышка: приподнятый косинус в шестой степени, то есть узкий луч, а
    -- не ровное дыхание.
    --
    -- Входит в определение дважды, но share тут не поможет вовсе, а не
    -- просто дорог: одно использование живёт внутри oversample, то есть в
    -- другом Env, а кэш share ключуется по Env. Разделять нечего, была бы
    -- чистая трата памяти.
    beam =
      mapSig (\x -> ((1 + cos x) / 2) ** 6) $
        phase (constant pulseHz) + constant (2 * pi * flash)

    -- Стержень должен читаться узкой полосой, поэтому резонанс высокий, а
    -- катофф открывается на вспышке. Оверсэмплинг вокруг фильтра обязателен:
    -- tanh в его обратной связи иначе заворачивает верх.
    voice =
      saw (constant freq)
        & oversample 4 (ladder (constant (freq * 2) + constant (freq * 8) * beam) 0.9)
        & (* (beam * constant 0.25))
